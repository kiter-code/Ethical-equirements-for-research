"""
prompts.py — системные промпты ролей и сборка сообщений для LLM.

ПРАКТИКА 4. Что делает студент:
  1. переписать ANALYST_PROMPT под свой домен, заменив примеры на доменные
  2. написать промпт для второй роли (и остальных, если ролей больше)
  3. реализовать build_messages() — сборку контекста в список сообщений

Критерии приёмки:
  - в orchestrator.py нет ни одной строки промпта, все здесь
  - у каждой роли свой системный промпт, не общий на всех
  - в промпте есть few-shot примеры, и они из вашего домена, а не из шаблона
  - ответ модели опирается на переданные чанки: подмена исходных данных меняет ответ

Промпт-инжиниринг как код означает ровно это: промпт — версионируемый артефакт,
который правится в git и виден в диффе, а не строка, склеенная где-то в цикле.

Про порядок блоков. Из Л4: «потеря в середине» — модель хуже усваивает то, что
лежит в середине длинного промпта. Поэтому инструкции держите в начале, найденные
фрагменты — ближе к концу, а сам вопрос — последним.
"""

from contracts import Chunk, Message

# --- Образец: роль «аналитик». Замените домен и примеры на свои (П4). ---

ANALYST_PROMPT = """Ты аналитик справочной системы по научной этике.
Отвечай только на основании переданных фрагментов, не восполняй пробелы общими знаниями.
К каждому фактическому выводу добавляй ссылку из заголовка фрагмента: [файл, стр. N]
или [файл], если страницы нет. Не выдумывай имена файлов и номера страниц.
Если данных недостаточно, скажи: «В базе знаний нет ответа на этот вопрос».
Отвечай кратко по-русски. Следующие примеры вымышлены и не являются источниками.

Вопрос: Что запрещено при публикации? Фрагмент: [пример.pdf, стр. 2] Плагиат запрещён.
Ответ: Плагиат запрещён. [пример.pdf, стр. 2]
Вопрос: Кто утверждает состав комитета? Фрагмент: [пример.pdf, стр. 2] Комитет рассматривает обращения.
Ответ: В базе знаний нет ответа на этот вопрос.
"""

VERIFIER_PROMPT = """Ты проверяешь утверждения о научной этике по переданным фрагментам.
Сопоставь утверждение с текстом: подтверди или опровергни только при наличии основания,
приведи ссылку из заголовка фрагмента без выдуманных страниц. Если доказательств
недостаточно, скажи, что подтвердить утверждение нельзя. Не достраивай факты.
Примеры вымышлены и не являются источниками.

Утверждение: Плагиат запрещён. Фрагмент: [пример.pdf, стр. 2] Плагиат запрещён.
Ответ: Подтверждается: плагиат запрещён. [пример.pdf, стр. 2]
Утверждение: Комитет рассматривает обращения за неделю. Фрагмент: [пример.pdf] Комитет рассматривает обращения.
Ответ: Подтвердить срок нельзя: во фрагменте он не указан.
"""

CLARIFIER_PROMPT = """Ты уточняешь вопросы о научной этике и работе этического комитета.
Определи недостающее условие и задай один конкретный вопрос, не делая окончательных
выводов и не выдумывая нормы. Используй фрагменты только как контекст; если ссылаешься
на факт из них, укажи источник ровно как в заголовке. Примеры вымышлены.

Вопрос: Какие требования к моему исследованию? Данных о его участниках нет.
Ответ: В исследовании участвуют люди или животные?
Вопрос: Уточни, можно ли опубликовать работу. Не указан вклад участников.
Ответ: Какой вклад в работу внёс каждый из предполагаемых авторов?
"""

SYSTEM_PROMPTS: dict[str, str] = {
    "analyst": ANALYST_PROMPT,
    "verifier": VERIFIER_PROMPT,
    "clarifier": CLARIFIER_PROMPT,
}


def format_chunks(chunks: list[Chunk]) -> str:
    """Развернуть найденные фрагменты в текстовый блок. Готово, менять не нужно."""
    if not chunks:
        return "(база знаний ничего не вернула)"
    # Страница печатается, только когда она есть: у markdown и текстовых файлов
    # page = 0, и «стр. 0» в каждом фрагменте учит модель дописывать в ссылку
    # номер, которого в контексте нет.
    return "\n\n".join(
        f"[{c.source}, стр. {c.page}] (близость {c.score})\n{c.text}" if c.page
        else f"[{c.source}] (близость {c.score})\n{c.text}"
        for c in chunks
    )


def build_messages(role: str, question: str, chunks: list[Chunk],
                   history: list[Message]) -> list[dict]:
    """Собрать список сообщений для LLM.

    Порядок, который стоит собрать:
      1. system  — SYSTEM_PROMPTS[role]
      2. история диалога из history (роль и текст как есть)
      3. user    — найденные фрагменты через format_chunks() плюс сам вопрос

    Формат каждого элемента: {"role": "system"|"user"|"assistant", "content": "..."}

    Ловушка: history приходит из памяти в хронологическом порядке — не переворачивайте
    его. И не кладите фрагменты в system: они меняются от запроса к запросу, а system
    должен оставаться стабильным.
    """
    return (
        [{"role": "system", "content": SYSTEM_PROMPTS[role]}]
        + [{"role": message.role, "content": message.content} for message in history]
        + [{"role": "user", "content": f"Фрагменты базы знаний:\n{format_chunks(chunks)}\n\nВопрос пользователя:\n{question}"}]
    )
